// Regenerates electron/data/resource-nodes.ts from The Hidden Gaming Lair's node
// dataset (CBOR). Provides resource type + purity per node (missing from saves).
//   node scripts/data/build-node-data.cjs
// Requires the `cbor-x` dev dependency.
//
// The URL contains a content hash. If th.gl updates their data, find the current
// path in the page source of https://satisfactory.th.gl/maps/World (search for
// "nodesPaths") and update NODES_URL below.
const fs = require('node:fs');
const path = require('node:path');
const { decode } = require('cbor-x');

const ROOT = path.resolve(__dirname, '../..');
const NODES_URL =
  'https://cdn.th.gl/satisfactory/nodes/world.bdf8828d94e2430cec62da2471d64667.raw';
const OUT = path.join(ROOT, 'electron/data/resource-nodes.ts');

// Infinite resource nodes (exclude deposits, wells, creatures, flora).
const RES = /^(OreIron|OreCopper|OreGold|Coal|Stone|RawQuartz|Sulfur|OreBauxite|OreUranium|SAM|LiquidOil)(_RP_(Pure|Inpure))?$/;
// Resource wells (fracking): oil / nitrogen / water. No purity on the well core.
const WELL = /^(LiquidOil|NitrogenGas|Water)_Well$/;
const purity = (t) => (/_RP_Pure$/.test(t) ? 'pure' : /_RP_Inpure$/.test(t) ? 'impure' : 'normal');

(async () => {
  console.log('fetching', NODES_URL);
  const res = await fetch(NODES_URL, { headers: { 'User-Agent': 'satisfactory-workbench' } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const groups = decode(new Uint8Array(await res.arrayBuffer()));

  const rows = [];
  const wells = [];
  for (const g of groups) {
    // th.gl (rx, ry) -> game (gameX = ry, gameY = rx); verified 459/459 exact.
    if (RES.test(g.type)) {
      const r = g.type.replace(/_RP_(Pure|Inpure)$/, '');
      const p = purity(g.type);
      for (const s of g.spawns) rows.push([r, p, Math.round(s.p[1]), Math.round(s.p[0]), Math.round(s.p[2])]);
    } else if (WELL.test(g.type)) {
      const r = g.type.replace(/_Well$/, '');
      for (const s of g.spawns) wells.push([r, Math.round(s.p[1]), Math.round(s.p[0]), Math.round(s.p[2])]);
    }
  }

  const nodeLines = rows.map((r) => `  [${JSON.stringify(r[0])}, "${r[1]}", ${r[2]}, ${r[3]}, ${r[4]}],`);
  const wellLines = wells.map((w) => `  [${JSON.stringify(w[0])}, ${w[1]}, ${w[2]}, ${w[3]}],`);
  const ts =
    '// AUTO-GENERATED by scripts/data/build-node-data.cjs from The Hidden Gaming Lair.\n' +
    '// Coordinates in game space (gameX = thgl.y, gameY = thgl.x). Standard (non-randomized) map.\n' +
    'export type RefPurity = "pure" | "normal" | "impure";\n' +
    '/** [resource, purity, x, y, z] — infinite resource nodes for the standard world map. */\n' +
    'export const RESOURCE_NODES: [string, RefPurity, number, number, number][] = [\n' +
    nodeLines.join('\n') +
    '\n];\n' +
    '/** [resource, x, y, z] — resource well cores (oil / nitrogen / water). */\n' +
    'export const RESOURCE_WELLS: [string, number, number, number][] = [\n' +
    wellLines.join('\n') +
    '\n];\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, ts);
  console.log(`wrote ${path.relative(ROOT, OUT)} with ${rows.length} nodes, ${wells.length} wells`);
})().catch((e) => { console.error(e); process.exit(1); });
